// Server-only owner TOTP workflow. Tokens stay in the verified session
// capability and encrypted HttpOnly cookies; browser responses contain no JWT.
const {
  sealCookiePayload, openCookiePayload, readCookie
} = require("./session.js");
const { providerFailure, diagnosticsEnabled, diagnostic } = require("./mfa-diagnostics.cjs");
const { restartWindow, eligiblePendingFactor } = require("./mfa-pending-restart.cjs");

const BASE = "/api/portal/security";
const CHALLENGE_COOKIE = "__Host-rexbid_mfa_challenge";
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const headers = {
  "Content-Type": "application/json; charset=UTF-8", "Cache-Control": "private, no-store",
  "Pragma": "no-cache", "Referrer-Policy": "no-referrer", "X-Content-Type-Options": "nosniff",
  "Vary": "Cookie", "X-Robots-Tag": "noindex, nofollow"
};
const challengeCookie = (value = "", age = 0) => `${CHALLENGE_COOKIE}=${encodeURIComponent(value)}; Path=/; Max-Age=${Math.max(0, Math.floor(age))}; Secure; HttpOnly; SameSite=Strict`;

function reply(data, status = 200, cookies = []) {
  const result = new Headers(headers);
  for (const cookie of cookies) result.append("Set-Cookie", cookie);
  return new Response(JSON.stringify(data), { status, headers: result });
}
function exactKeys(body, expected) {
  return body && typeof body === "object" && !Array.isArray(body)
    && Object.keys(body).every(key => expected.includes(key)) && expected.every(key => Object.hasOwn(body, key));
}
function totpFactors(identity) {
  return (Array.isArray(identity?.mfa_factors) ? identity.mfa_factors : [])
    .filter(factor => UUID.test(factor?.id || "") && factor.factor_type === "totp" && ["verified", "unverified"].includes(factor.status))
    .map(factor => ({ id: factor.id, factor_type: "totp", status: factor.status,
      friendly_name: typeof factor.friendly_name === "string" ? factor.friendly_name.slice(0, 120) : "" }));
}
const hasVerifiedMfa = identity => identity?.mfa_has_verified_factor === true
  || identity?.mfa_factors?.some(factor => factor.status === "verified") === true;
function qrImageSource(value) {
  if (typeof value !== "string" || !value || value.length > 1048576) return null;
  let svg = value;
  if (/^data:/i.test(value)) {
    const comma = value.indexOf(",");
    if (comma < 0) return null;
    const header = value.slice(0, comma);
    if (!/^data:image\/svg\+xml(?:;charset=utf-8)?(?:;base64)?$/i.test(header)) return null;
    const encoded = value.slice(comma + 1);
    try {
      if (/;base64$/i.test(header)) {
        if (!encoded || !/^[A-Za-z0-9+/]+={0,2}$/.test(encoded) || encoded.length % 4 !== 0) return null;
        svg = new TextDecoder("utf-8", { fatal: true }).decode(Uint8Array.from(atob(encoded), character => character.charCodeAt(0)));
      } else svg = decodeURIComponent(encoded);
    } catch { return null; }
  }
  // Supabase REST uses SVGo: an XML declaration, generator comment and a
  // rectangle per QR module. Accept this inert preamble, never DTDs/entities
  // or arbitrary processing instructions. Keep explicit size bounds.
  svg = svg.trimStart()
    .replace(/^<\?xml\s+version="1\.0"(?:\s+encoding="UTF-8")?\s*\?>\s*/i, "")
    .replace(/^<!-- Generated by SVGo -->\s*/, "");
  if (svg.length > 524288 || !/^\s*<svg\b/i.test(svg) || /<!DOCTYPE|<!ENTITY|<\?/i.test(svg)) return null;
  // Accept raw SVG or an exact SVG data URI. Normalize both without inserting
  // markup. The browser additionally parses
  // and checks its strict SVG element/attribute allowlist before using <img>.
  const source = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;
  return source.length <= 1572864 ? source : null;
}
function enrolledFactor(payload) {
  if (!UUID.test(payload?.id || "") || payload?.type !== "totp"
    || typeof payload?.totp?.secret !== "string" || !/^[A-Z2-7]{16,128}$/.test(payload.totp.secret)
    || typeof payload?.totp?.uri !== "string" || payload.totp.uri.length > 4096) return null;
  let uri;
  try { uri = new URL(payload.totp.uri); } catch { return null; }
  if (uri.protocol !== "otpauth:" || uri.hostname !== "totp" || uri.searchParams.get("secret") !== payload.totp.secret) return null;
  const qr = qrImageSource(payload.totp.qr_code);
  return { id: payload.id, factor_type: "totp", secret: payload.totp.secret, uri: payload.totp.uri, qr_code: qr };
}

function createOwnerMfaRouteHandler({ provider, resolveOwnerSession, verifiedSessionCookie, readJson, now = () => Math.floor(Date.now() / 1000), cryptoImpl = globalThis.crypto } = {}) {
  if (!provider || typeof resolveOwnerSession !== "function" || typeof verifiedSessionCookie !== "function" || typeof readJson !== "function") throw new TypeError("Owner MFA server capabilities are required");
  return async function handle(request, env) {
    const path = new URL(request.url).pathname;
    if (![BASE, `${BASE}/enroll`, `${BASE}/challenge`, `${BASE}/verify`, `${BASE}/restart-pending`].includes(path)) return null;
    const operation = path === BASE ? "read" : path.slice(BASE.length + 1);
    const window = restartWindow(request, env, now());
    if (operation === "restart-pending" && !window) return reply({ ok: false, error: "Niedostępne." }, 404);
    let stage = "method", factors = null;
    const trace = diagnosticsEnabled(request, env);
    const requestId = trace ? cryptoImpl.randomUUID() : null;
    const send = (data, status = 200, cookies = [], failure = null) => reply({ ...data,
      ...(trace ? { diagnostic: diagnostic({ requestId, operation, stage, status, failure, factors }) } : {})
    }, status, cookies);
    const rejected = (error, cookies) => {
      const failure = providerFailure(error, operation);
      return send({ ok: false, code: failure.code, error: "Nie udało się zakończyć operacji MFA." }, failure.status, cookies, failure);
    };
    const method = operation === "read" ? "GET" : "POST";
    if (request.method !== method) return send({ ok: false, error: "Metoda niedozwolona." }, 405);
    stage = "owner_session";
    let state;
    try { state = await resolveOwnerSession(request, env, `owner_mfa_${operation}`); }
    catch (error) { return rejected(error, []); }
    if (state.status !== 200) {
      stage = state.stage || "owner_session";
      return send({ ok: false, error: state.status === 401 ? "Wymagane logowanie." : state.status === 403 ? "Brak dostępu." : state.status === 429 ? "Zbyt wiele prób. Spróbuj później." : "Zabezpieczenia konta są chwilowo niedostępne." }, state.status, state.cookies, state.failure);
    }
    factors = totpFactors(state.identity);
    stage = "factor_state";
    if (operation === "read") return send({ ok: true, owner: true, assurance_level: state.identity.assurance_level || null, factors, has_verified_factor: hasVerifiedMfa(state.identity),
      ...(window ? { restart_pending_available: !!eligiblePendingFactor(state.identity, window.before) } : {}) }, 200, state.cookies);
    stage = "input";
    const body = await readJson(request);
    if (operation === "restart-pending") {
      stage = "restart_preflight";
      const pending = eligiblePendingFactor(state.identity, window.before);
      const blocked = cookies => send({ ok: false, code: "MFA_RESTART_BLOCKED", error: "Stan zabezpieczeń zmienił się. Niczego nie usunięto." }, 409, cookies, { code: "MFA_RESTART_BLOCKED" });
      if (!exactKeys(body, ["factor_id"]) || !pending || pending.id !== body.factor_id) return blocked(state.cookies);
      if (typeof provider.unenrollPendingTotp !== "function") return rejected(null, state.cookies);
      // Repeat the owner/account check as well as the provider factor check.
      stage = "restart_recheck";
      let fresh;
      try { fresh = await resolveOwnerSession(request, env, "owner_mfa_restart_pending"); }
      catch (error) { return rejected(error, state.cookies); }
      if (fresh.status !== 200 || fresh.user?.id !== state.user.id || fresh.identity?.issuer !== state.identity.issuer
        || fresh.identity?.subject !== state.identity.subject || !restartWindow(request, env, now())
        || eligiblePendingFactor(fresh.identity, window.before)?.id !== body.factor_id) return blocked(fresh.cookies || state.cookies);
      try {
        stage = "upstream_unenroll_pending";
        await provider.unenrollPendingTotp(env, fresh.session.access_token, { factorId: body.factor_id, before: window.before,
          issuer: fresh.identity.issuer, subject: fresh.identity.subject });
        stage = "restart_readback";
        const after = await resolveOwnerSession(request, env, "owner_mfa_restart_pending");
        if (after.status !== 200 || after.user?.id !== state.user.id || after.identity?.issuer !== state.identity.issuer
          || after.identity?.subject !== state.identity.subject || after.identity?.mfa_factors_complete !== true
          || after.identity?.mfa_factor_count !== 0 || hasVerifiedMfa(after.identity)) {
          return rejected({ code: "MFA_RESTART_UNCERTAIN" }, [...fresh.cookies, challengeCookie()]);
        }
        factors = [];
        stage = "complete";
        return send({ ok: true, removed_pending: true }, 200, [...after.cookies, challengeCookie()]);
      } catch (error) { return rejected(error, [...fresh.cookies, challengeCookie()]); }
    }
    if (operation === "enroll") {
      if (!exactKeys(body, [])) return send({ ok: false, error: "Nieprawidłowe dane." }, 400, state.cookies);
      // A compromised first-factor session cannot replace/bypass an existing
      // verified second factor by enrolling its own authenticator.
      if (state.identity.assurance_level !== "aal2" && hasVerifiedMfa(state.identity)) return send({ ok: false, error: "Najpierw potwierdź istniejące zabezpieczenie MFA." }, 403, state.cookies);
      stage = "enrollment_guard";
      // An unfinished enrollment already owns its name in Supabase. Never
      // retry creating it, replace it, or delete factors automatically.
      if (factors.some(factor => factor.status === "unverified")) return send({ ok: false, code: "MFA_ENROLLMENT_PENDING", error: "Dokończ istniejącą konfigurację aplikacji uwierzytelniającej." }, 409, state.cookies, { code: "MFA_ENROLLMENT_PENDING" });
      if (typeof provider.enrollTotp !== "function") return send({ ok: false, error: "MFA jest chwilowo niedostępne." }, 503, state.cookies);
      try {
        stage = "upstream_enroll";
        const payload = await provider.enrollTotp(env, state.session.access_token);
        stage = "enrollment_payload";
        const factor = enrolledFactor(payload);
        if (!factor) throw Object.assign(new Error("INVALID_MFA_ENROLLMENT"), { code: "MFA_INVALID_ENROLLMENT" });
        stage = "complete";
        return send({ ok: true, factor }, 201, state.cookies);
      } catch (error) { return rejected(error, state.cookies); }
    }
    if (!exactKeys(body, operation === "challenge" ? ["factor_id"] : ["factor_id", "challenge_id", "code"])
      || !UUID.test(body.factor_id) || !factors.some(factor => factor.id === body.factor_id)
      || (operation === "verify" && (!UUID.test(body.challenge_id) || typeof body.code !== "string" || !/^\d{6}$/.test(body.code)))) return send({ ok: false, error: "Nieprawidłowe dane zabezpieczenia." }, 400, state.cookies);
    const selectedFactor = factors.find(factor => factor.id === body.factor_id);
    if (state.identity.assurance_level !== "aal2" && selectedFactor.status !== "verified"
      && hasVerifiedMfa(state.identity)) return send({ ok: false, error: "Najpierw potwierdź istniejące zabezpieczenie MFA." }, 403, state.cookies);
    if (operation === "challenge") {
      if (typeof provider.challengeTotp !== "function") return send({ ok: false, error: "MFA jest chwilowo niedostępne." }, 503, state.cookies);
      try {
        stage = "upstream_challenge";
        const challenge = await provider.challengeTotp(env, state.session.access_token, body.factor_id);
        stage = "challenge_payload";
        if (!UUID.test(challenge?.id || "") || !Number.isFinite(challenge?.expires_at) || challenge.expires_at <= now()) throw Object.assign(new Error("INVALID_MFA_CHALLENGE"), { code: "MFA_INVALID_CHALLENGE" });
        const expiresAt = Math.min(challenge.expires_at, now() + 300);
        const receipt = await sealCookiePayload({
          challenge_id: challenge.id, factor_id: body.factor_id, user_id: state.user.id,
          issuer: state.identity.issuer, subject: state.identity.subject, expires_at: expiresAt
        }, env.REXBID_AUTH_COOKIE_SECRET, cryptoImpl);
        stage = "complete";
        return send({ ok: true, challenge_id: challenge.id, expires_at: expiresAt }, 200,
          [...state.cookies, challengeCookie(receipt, expiresAt - now())]);
      } catch (error) { return rejected(error, state.cookies); }
    }
    stage = "challenge_receipt";
    const receipt = await openCookiePayload(readCookie(request, CHALLENGE_COOKIE), env.REXBID_AUTH_COOKIE_SECRET, cryptoImpl);
    if (!receipt || receipt.expires_at <= now() || receipt.user_id !== state.user.id
      || receipt.issuer !== state.identity.issuer || receipt.subject !== state.identity.subject
      || receipt.factor_id !== body.factor_id || receipt.challenge_id !== body.challenge_id) return send({ ok: false, error: "Weryfikacja wygasła. Rozpocznij ją ponownie." }, 403, [...state.cookies, challengeCookie()]);
    if (typeof provider.verifyTotp !== "function") return send({ ok: false, error: "MFA jest chwilowo niedostępne." }, 503, state.cookies);
    try {
      stage = "upstream_verify";
      const session = await provider.verifyTotp(env, state.session.access_token, {
        factorId: body.factor_id, challengeId: body.challenge_id, code: body.code
      });
      stage = "session_verification";
      const cookie = await verifiedSessionCookie(env, state, session, body.factor_id);
      stage = "complete";
      return send({ ok: true, assurance_level: "aal2" }, 200, [cookie, challengeCookie()]);
    } catch (error) {
      return rejected(error, state.cookies);
    }
  };
}

module.exports = { createOwnerMfaRouteHandler };
